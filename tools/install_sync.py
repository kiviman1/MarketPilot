"""Install a private desktop companion from the same source; no addon ZIP."""
import argparse
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
FILES = ("sync/__init__.py", "sync/engine.py", "sync/app.py",
         "assets/MarketPilot-CurseForge.png")
README = """MarketPilot Sync

Open the desktop shortcut, select the AHledger market and click Simdi guncelle.
The existing MarketPilotDev addon must support ExternalData.lua.
After success, use /reload then /mpdev external in WoW.

This first version runs with the already installed Python 3 + Tk runtime.
It downloads only when requested and writes only ExternalData.lua.
It does not update addon code or change local WoW history / settings.
Data source: AHledger https://ahledger.com
See repository docs/AHLEDGER_SYNC.md for the full contract and checks.
"""


def install(destination):
    destination = Path(destination).resolve()
    if destination.name != "MarketPilot Sync" or destination.is_relative_to(ROOT):
        raise ValueError("Use a separate directory named MarketPilot Sync")
    generated = {name: (ROOT / name).read_bytes() for name in FILES}
    generated["README.txt"] = README.encode("utf-8")
    generated["MarketPilot Sync.pyw"] = b"from sync.app import main\nmain()\n"
    # Reuse the addon's 64px BGRA icon as a Windows DIB, without an imaging
    # dependency. ICO stores bottom-up pixels plus a separate transparency mask.
    icon = (ROOT / "src/MarketPilot/Media/Icon.tga").read_bytes()
    if (icon[2] != 2 or icon[16] != 32 or struct.unpack_from("<HH", icon, 12) != (64, 64)
            or len(icon) != 18 + 64 * 64 * 4):
        raise ValueError("Expected the existing 64px MarketPilot BGRA icon")
    pixels = icon[18:]
    if icon[17] & 32:
        pixels = b"".join(pixels[row * 256:(row + 1) * 256] for row in range(63, -1, -1))
    dib = struct.pack("<IiiHHIIiiII", 40, 64, 128, 1, 32, 0, len(pixels), 0, 0, 0, 0) + pixels + bytes(512)
    generated["MarketPilot Sync.ico"] = struct.pack("<HHH", 0, 1, 1) + struct.pack(
        "<BBBBHHII", 64, 64, 0, 0, 1, 32, len(dib), 22) + dib
    if destination.exists():
        # Python bytecode is generated by the interpreter, not user data.
        existing = {p.relative_to(destination).as_posix() for p in destination.rglob("*")
                    if p.is_file() and "__pycache__" not in p.parts}
        extra = existing - generated.keys()
        if extra:
            raise ValueError(f"Unexpected files in desktop installation: {sorted(extra)}")
    for relative in generated:
        if not (destination / relative).resolve().is_relative_to(destination):
            raise ValueError("Desktop file resolves outside its directory")
    for relative, contents in generated.items():
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(contents)
    print(f"Desktop app: {destination}")
    print(f"Launcher: {Path(sys.executable).with_name('pythonw.exe')} {destination / 'MarketPilot Sync.pyw'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, required=True)
    install(parser.parse_args().destination)
